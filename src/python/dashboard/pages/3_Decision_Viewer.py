"""
Page 3 - Credit Decision Viewer
Search applicant, SHAP waterfall, RAG-generated decision letter citing the RBI PDF
"""
import ast
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[4]))  # project root

import plotly.graph_objects as go
import streamlit as st

from src.python.dashboard import theme
from src.python.dashboard.db_utils import get_duckdb_connection
from src.python.scoring.decision_rules import decision_from_tier, risk_tier_from_proba  # single source of truth

theme.setup("Decision Viewer", "🔍")
theme.page_header("🔍", "Credit Decision Viewer", "Why was this applicant approved or rejected? — SHAP factors + RBI-grounded letter")

con = get_duckdb_connection()
try:
    available_ids = con.execute("SELECT member_id_hash FROM prediction_explanations LIMIT 200").fetchdf()["member_id_hash"].tolist()
except Exception:
    available_ids = []

if not available_ids:
    theme.empty_state("No explanations yet", "Run the SHAP explainer first (prediction_explanations is empty).", "🧠")
    st.stop()

with st.container(border=True):
    left, right = st.columns([1, 2])
    with left:
        search_mode = st.radio("Search mode", ["Select from list", "Manual input"], horizontal=False)
    with right:
        if search_mode == "Select from list":
            applicant_id = st.selectbox("Applicant ID", available_ids)
        else:
            applicant_id = st.text_input("member_id_hash", placeholder="paste an applicant hash")

if not applicant_id:
    st.stop()

row = con.execute("SELECT * FROM prediction_explanations WHERE member_id_hash = ?", [applicant_id]).fetchdf()
if row.empty:
    theme.empty_state("Applicant not found", "Check the hash and try again.", "🔎")
    st.stop()

proba = float(row.iloc[0]["predicted_proba"])
raw_features = row.iloc[0]["top_shap_features_json"]
try:
    top_features = json.loads(raw_features)
except (json.JSONDecodeError, TypeError):
    top_features = ast.literal_eval(raw_features)

risk_tier = risk_tier_from_proba(proba)
decision = decision_from_tier(risk_tier)

st.write("")
b1, b2 = st.columns([3, 2])
with b1:
    theme.decision_banner(decision, proba, risk_tier)
with b2:
    theme.kpi_row([{"label": "Default probability", "value": f"{proba:.2%}", "hint": f"tier {risk_tier.replace('_', ' ')}",
                    "accent": theme.RISK_COLORS[risk_tier]}])

theme.section("Decision factors", "Red pushes risk up, green pulls it down (SHAP)")
features = [f["feature"].replace("_", " ") for f in top_features]
values = [f["shap_value"] for f in top_features]
fig = go.Figure(
    go.Waterfall(
        orientation="v", measure=["relative"] * len(features), x=features, y=values,
        text=[f"{v:+.3f}" for v in values], textposition="outside",
        increasing={"marker": {"color": theme.RISK_COLORS["VERY_HIGH"]}},
        decreasing={"marker": {"color": theme.RISK_COLORS["LOW"]}},
        connector={"line": {"color": "#CBD5E1"}},
    )
)
fig.update_layout(title="Feature contribution to the risk score")
st.plotly_chart(theme.style_fig(fig, height=400, legend=False), width="stretch")

theme.section("Decision letter", "Generated by RAG over the official RBI PDF + a local LLM")
if st.button("✨ Generate decision letter", type="primary"):
    with st.spinner("Retrieving RBI clauses and drafting the letter…"):
        try:
            from src.python.rag.credit_decision_explainer import generate_credit_decision_letter

            result = generate_credit_decision_letter(applicant_id)
        except Exception as e:
            st.error(f"Failed to generate the letter: {e}. Is the index built (`python -m src.python.rag.chroma_store`) and Ollama running (`ollama serve`)?")
            st.stop()

    q = result["quality_check"]
    theme.kpi_row(
        [
            {"label": "Generation time", "value": f"{result['llm_metadata']['latency_seconds']:.1f}s", "hint": result["llm_metadata"]["model"], "accent": theme.INDIGO},
            {"label": "Factor coverage", "value": f"{q['coverage_ratio']:.0%}", "hint": "SHAP factors mentioned", "accent": theme.TEAL if q["all_features_mentioned"] else theme.RISK_COLORS["HIGH"]},
            {"label": "RBI references", "value": str(len(result["regulation_references"])), "hint": "clauses retrieved", "accent": theme.VIOLET},
        ]
    )
    st.write("")
    with st.container(border=True):
        st.markdown(result["narrative"])
    with st.expander("📚 Regulatory references used", expanded=True):
        for ref in result["regulation_references"]:
            st.markdown(f"- {ref}")
    with st.expander("Quality check (raw)"):
        st.json(q)
else:
    theme.empty_state("No letter generated yet", "Click the button to draft a formal decision letter from the SHAP factors and RBI directions.", "📄")
